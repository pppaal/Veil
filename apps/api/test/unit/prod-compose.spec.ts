import { randomBytes } from 'node:crypto';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

import { ConfigService } from '@nestjs/config';

import { AppConfigService } from '../../src/common/config/app-config.service';
import { envSchema, type EnvConfig } from '../../src/common/config/env.schema';

// The production stack is configured in three places that have to move in
// lockstep with the API's boot gate: .env.prod.example (the operator's
// template), the secret generator in docs/vps-deploy-runbook.md §3, and the
// api service's explicit `environment:` map in docker-compose.prod.yml (which
// has no env_file, so a key the map does not forward never reaches the
// container). These tests follow the runbook end to end and boot the gate on
// exactly the environment compose would hand the container.

const ROOT = join(__dirname, '../../../..');
const read = (path: string): string => readFileSync(join(ROOT, path), 'utf8');

const parseDotenv = (source: string): Map<string, string> => {
  const values = new Map<string, string>();
  for (const line of source.split('\n')) {
    const match = /^([A-Z0-9_]+)=(.*)$/.exec(line.trim());
    if (match) values.set(match[1], match[2]);
  }
  return values;
};

// Keys the runbook §3 generator fills with `sed -i "s|^KEY=.*|KEY=$(...)|" .env.prod`.
const runbookGeneratedKeys = (runbook: string): string[] =>
  [...runbook.matchAll(/^sed -i "s\|\^([A-Z0-9_]+)=\.\*\|/gm)].map((match) => match[1]);

// A service's `command:` when it is a one-line flow sequence of double-quoted
// strings, which is JSON.
const serviceCommand = (compose: string, service: string): string[] => {
  const lines = compose.split('\n');
  const start = lines.indexOf(`  ${service}:`);
  expect(start).toBeGreaterThan(-1);
  const end = lines.findIndex((line, index) => index > start && /^ {2}\S/.test(line));
  const command = lines
    .slice(start, end === -1 ? undefined : end)
    .map((line) => /^ {4}command: (\[.*\])$/.exec(line)?.[1])
    .find(Boolean);
  if (!command) throw new Error(`${service} has no one-line command sequence`);
  return JSON.parse(command) as string[];
};

// The api service's `environment:` block. The file is plain block YAML; any
// shape this reader does not understand fails the test instead of being
// skipped, so it cannot silently miss a key.
const apiEnvironment = (compose: string): Map<string, string> => {
  const lines = compose.split('\n');
  const service = lines.indexOf('  api:');
  expect(service).toBeGreaterThan(-1);
  let index = lines.indexOf('    environment:', service);
  expect(index).toBeGreaterThan(service);
  const environment = new Map<string, string>();
  for (index += 1; index < lines.length; index += 1) {
    const line = lines[index];
    if (line.trim() === '' || line.trim().startsWith('#')) continue;
    if (!line.startsWith('      ')) break;
    const entry = /^ {6}([A-Z0-9_]+): (.*)$/.exec(line);
    if (!entry) throw new Error(`unexpected line in api environment: ${line}`);
    const value = entry[2];
    const quoted = /^"(.*)"$/.exec(value) ?? /^'(.*)'$/.exec(value);
    if (!quoted && /^[[{|>&*!"']/.test(value)) {
      throw new Error(`unsupported YAML value in api environment: ${line}`);
    }
    environment.set(entry[1], quoted ? quoted[1] : value);
  }
  return environment;
};

// docker compose interpolation of ${VAR}, ${VAR:-default} and ${VAR:?error}.
// `:?` makes compose refuse to create any container at all; inside the
// container, the entrypoint's preflight runs the boot gate before
// `prisma migrate deploy` (see preflight.spec.ts).
const interpolate = (value: string, dotenv: ReadonlyMap<string, string>): string =>
  value.replace(
    /\$\{([A-Z0-9_]+)(?::([-?])([^}]*))?\}/g,
    (_match, name: string, operator?: string, argument?: string) => {
      const set = dotenv.get(name);
      if (set !== undefined && set !== '') return set;
      if (operator === '-') return argument ?? '';
      if (operator === '?') throw new Error(`compose refuses to start: ${name} ${argument}`);
      return '';
    },
  );

const containerEnv = (dotenv: ReadonlyMap<string, string>): Record<string, string> => {
  const env: Record<string, string> = {};
  for (const [key, raw] of apiEnvironment(read('docker-compose.prod.yml'))) {
    env[key] = interpolate(raw, dotenv);
  }
  return env;
};

const bootGate = (env: Record<string, string>): void => {
  const parsed = envSchema.parse(env) as Record<string, unknown>;
  const configService = {
    get: (key: string) => parsed[key],
  } as unknown as ConfigService<EnvConfig, true>;
  new AppConfigService(configService).assertProductionReady();
};

// .env.prod as an operator ends up with after following the runbook: copied
// from the example, every secret generated by §3 (hex here, so a generated
// value can never break the URLs compose builds from it), and the audit
// attestation set once the external audit has cleared.
const operatorDotenv = (): Map<string, string> => {
  const dotenv = parseDotenv(read('.env.prod.example'));
  for (const key of runbookGeneratedKeys(read('docs/vps-deploy-runbook.md'))) {
    expect(dotenv.has(key)).toBe(true);
    dotenv.set(key, randomBytes(24).toString('hex'));
  }
  dotenv.set('VEIL_AUDITED_CRYPTO_ATTESTED', 'true');
  dotenv.set('VEIL_AUDIT_REPORT_SHA256', 'ab'.repeat(32));
  return dotenv;
};

describe('docker-compose.prod.yml + .env.prod.example + runbook', () => {
  it('the runbook generates every placeholder secret in .env.prod.example', () => {
    const left = [...operatorDotenv()]
      .filter(([, value]) => /replace-me/i.test(value))
      .map(([key]) => key);
    expect(left).toEqual([]);
  });

  it('the environment compose hands the api container passes the production boot gate', () => {
    const env = containerEnv(operatorDotenv());
    expect(env.VEIL_ENV).toBe('production');
    expect(() => bootGate(env)).not.toThrow();
  });

  it('compose refuses to start, before any migration, when the retired-handle pepper is missing', () => {
    for (const value of [undefined, '']) {
      const dotenv = operatorDotenv();
      if (value === undefined) dotenv.delete('VEIL_RETIRED_HANDLE_PEPPER');
      else dotenv.set('VEIL_RETIRED_HANDLE_PEPPER', value);
      expect(() => containerEnv(dotenv)).toThrow(/VEIL_RETIRED_HANDLE_PEPPER/);
    }
  });
});

describe('docker-compose.prod.yml redis', () => {
  // Rate-limit counters (keyed by a hash of the client IP), prekey-claim
  // budgets, group key distributions and refresh tokens (with user and device
  // ids) live in Redis with short TTLs. An append-only file would keep every
  // one of those writes, with its timestamp, on the persistent volume long
  // after the key expired; a snapshot holds only the keys alive when taken.
  it('keeps no append-only log of expired keys', () => {
    const command = serviceCommand(read('docker-compose.prod.yml'), 'redis');
    expect(command[0]).toBe('redis-server');
    const appendonly = command.indexOf('--appendonly');
    expect(appendonly).toBeGreaterThan(0);
    expect(command[appendonly + 1]).toBe('no');
    expect(command.filter((arg) => arg === '--appendonly')).toHaveLength(1);
  });

  // Refresh tokens exist only in Redis and the mobile app cannot yet
  // re-authenticate without one, so a restart must not wipe them.
  it('still snapshots the live keys', () => {
    const command = serviceCommand(read('docker-compose.prod.yml'), 'redis');
    const save = command.indexOf('--save');
    expect(save).toBeGreaterThan(0);
    expect(command[save + 1]).toMatch(/^\d+ \d+( \d+ \d+)*$/);
  });
});
